// TableStructure.swift
// One table's columns, indexes and constraints as the catalog reports them, for the structure
// editor. Expressions (defaults, generated columns, predicates, checks) stay raw server text.
// Engine-only details are optional fields; an engine leaves the ones it lacks nil.

import Foundation

nonisolated struct TableStructure: Sendable, Equatable {
  /// Engine identity of the table (`TableRef.sqlite`, `.postgresql(oid:)`, `.mysql`, `.duckdb`)
  var tableID: TableRef
  /// Schema (PostgreSQL, DuckDB, SQLite attached name) or database (MySQL)
  var schema: String
  var name: String
  /// In table order
  var columns: [Column]
  /// Every index, including the ones that back a primary key or unique constraint
  var indexes: [Index]
  var constraints: [Constraint]

  struct Column: Sendable, Equatable {
    /// 1-based position in the table
    var ordinal: Int
    var name: String
    /// Type as the engine displays it (`integer`, `character varying(20)`, `INTEGER`)
    var dataType: String
    var isNullable: Bool
    /// Raw DEFAULT expression text (`'x'`, `0`, `nextval('s'::regclass)`). Nil when none.
    var defaultExpression: String?
    var identity: Identity?
    var generated: Generated?
    var comment: String?
    /// MySQL `COLUMN_TYPE` (`int unsigned`, `enum('a','b')`)
    var columnType: String?
    /// MySQL `EXTRA` (`auto_increment`, `on update CURRENT_TIMESTAMP`)
    var extra: String?
    var characterSet: String?
    var collation: String?
  }

  /// How the engine fills a column without a value
  enum Identity: Sendable, Equatable {
    /// MySQL `AUTO_INCREMENT`, SQLite `INTEGER PRIMARY KEY AUTOINCREMENT`
    case autoIncrement
    /// PostgreSQL `GENERATED ALWAYS AS IDENTITY`
    case always
    /// PostgreSQL `GENERATED BY DEFAULT AS IDENTITY`
    case byDefault
  }

  struct Generated: Sendable, Equatable {
    /// Raw expression text. Nil when the engine does not report it (SQLite).
    var expression: String?
    /// STORED; false means VIRTUAL
    var isStored: Bool
  }

  struct Index: Sendable, Equatable {
    var name: String
    /// Key parts in order
    var keys: [Key]
    var isUnique: Bool
    /// Backs the primary key
    var isPrimary: Bool
    /// `btree`, `hash`, `gin`, ... Nil when the engine has one kind only (SQLite).
    var method: String?
    var isPartial: Bool
    /// Raw WHERE text of a partial index. Nil when not partial or not reported.
    var predicate: String?

    enum Key: Sendable, Equatable {
      case column(String)
      /// Raw expression text. Nil when the engine does not report it (SQLite).
      case expression(String?)
    }
  }

  struct Constraint: Sendable, Equatable {
    /// Nil when the engine does not name it (SQLite primary and foreign keys)
    var name: String?
    var kind: Kind
    /// Constrained columns in key order. Empty for a table-level check.
    var columns: [String]

    enum Kind: Sendable, Equatable {
      case primaryKey
      /// A unique constraint. Its backing index has the same name where the engine has one.
      case unique
      case foreignKey(ForeignKeyReference)
      /// Raw CHECK expression text
      case check(String)
    }
  }

  struct ForeignKeyReference: Sendable, Equatable {
    var schema: String
    var table: String
    /// Matches `Constraint.columns` position by position
    var columns: [String]
    var onUpdate: ForeignKeyAction
    var onDelete: ForeignKeyAction
  }
}
