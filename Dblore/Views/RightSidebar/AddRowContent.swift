//  Add Row form of the data viewer in the right sidebar: one field per column, checked against
//  the column type. Add and Cancel sit in the sidebar footer. An empty field is left out of the
//  INSERT (database default); NULL is set with the field's NULL button.
//

import SwiftUI

struct AddRowContent: View {
  @Bindable var viewModel: NotebookViewModel

  /// Rebuilds the fields when the viewer shows another relation or other columns
  private var formKey: String {
    let relation = "\(viewModel.dataViewer?.schema ?? "").\(viewModel.dataViewer?.name ?? "")"
    let columns = viewModel.editorResult?.columns.map(\.name) ?? []
    return ([relation] + columns).joined(separator: "\u{0}")
  }

  var body: some View {
    ScrollView {
      VStack(alignment: .leading, spacing: Spacing.md) {
        VStack(alignment: .leading, spacing: Spacing.xs) {
          Text("Table")
            .font(.caption)
            .foregroundColor(.foregroundSubtle)

          Text(viewModel.dataViewer?.title ?? "")
            .font(.mono)
            .foregroundColor(.foreground)
            .lineLimit(1)
            .truncationMode(.middle)
        }

        Divider()

        if viewModel.addRowFields.isEmpty {
          Text("No columns loaded")
            .font(.caption)
            .foregroundColor(.foregroundMuted)
        }

        ForEach($viewModel.addRowFields) { $field in
          NewRowFieldEditor(field: $field, error: field.validationError)
        }
      }
      .frame(maxWidth: .infinity, alignment: .topLeading)
    }
    .onChange(of: formKey) {
      Task { await viewModel.prepareAddRowFields() }
    }
  }
}

/// One column of the Add Row form or of Row Details: name and type, the input, and its
/// validation error
struct NewRowFieldEditor: View {
  @Binding var field: NewRowField
  /// Error shown under the input (and its red outline): the field's own for Add Row, the draft's
  /// against the row for Row Details
  let error: String?
  /// False for an existing row: no "Default" choice, no DEFAULT hints
  var allowsDefault = true
  /// Shows the value as selectable text, without NULL or Beautify
  var isReadOnly = false
  /// Marks a draft that differs from the row
  var isDirty = false

  var body: some View {
    VStack(alignment: .leading, spacing: Spacing.xs) {
      header
      input
      if let error {
        HStack(spacing: Spacing.xs) {
          Image(systemName: "exclamationmark.triangle.fill")
            .font(.caption)
            .foregroundColor(.destructive)

          Text(error)
            .font(.caption)
            .foregroundColor(.destructive)
        }
        .padding(.horizontal, Spacing.xs)
      }
    }
  }

  private var header: some View {
    HStack(spacing: Spacing.xs) {
      if isDirty {
        Circle()
          .fill(Color.accent)
          .frame(width: 6, height: 6)
      }

      if field.isPrimaryKey {
        Image(systemName: "key")
          .font(.caption)
          .foregroundColor(.foregroundSubtle)
          .help("Primary key")
      }

      Text(field.name)
        .font(.monoMedium)
        .foregroundColor(.foreground)
        .lineLimit(1)
        .truncationMode(.middle)

      Text(field.type.lowercased())
        .font(.caption)
        .foregroundColor(.foregroundSubtle)
        .lineLimit(1)

      Spacer(minLength: Spacing.xs)

      if !field.isGenerated && !isReadOnly {
        if field.kind == .json && !field.isNull {
          FloatingPanelButton(icon: "curlybraces", helpText: "Beautify JSON", action: beautify)
            .disabled(field.text.isEmpty)
        }

        if field.isNullable || field.isNull {
          Button("NULL") { field.isNull.toggle() }
            .buttonStyle(GhostButtonStyle(isActive: field.isNull))
            .controlSize(.small)
            .help(field.isNull ? "Use the typed value" : "Set NULL")
        }
      }
    }
  }

  @ViewBuilder
  private var input: some View {
    if isReadOnly {
      if field.isNull {
        placeholderBox("NULL")
      } else {
        placeholderBox(field.text, italic: false)
          .textSelection(.enabled)
      }
    } else if field.isGenerated {
      placeholderBox("Generated by the database")
    } else if field.isNull {
      placeholderBox("NULL")
    } else if field.kind == .boolean {
      Picker("", selection: $field.text) {
        if allowsDefault {
          Text("Default").tag("")
        }
        Text("true").tag("true")
        Text("false").tag("false")
      }
      .labelsHidden()
      .pickerStyle(.segmented)
    } else {
      TextField(
        placeholder, text: $field.text,
        axis: field.kind == .text || field.kind == .json ? .vertical : .horizontal
      )
      .lineLimit(1...8)
      .textFieldStyle(.plain)
      .font(.monoMedium)
      .padding(Spacing.sm)
      .background(Color.controlBackground)
      .clipShape(RoundedRectangle(cornerRadius: CornerRadius.md))
      .overlay(
        HairlineBorder(
          shape: RoundedRectangle(cornerRadius: CornerRadius.md),
          color: error != nil ? .destructive : .border)
      )
    }
  }

  /// Input hint: an empty field is the column default, unless defaults are off
  private var placeholder: String {
    guard allowsDefault else {
      switch field.kind {
      case .date: return "yyyy-MM-dd"
      case .timestamp: return "yyyy-MM-dd HH:mm:ss"
      case .uuid: return "UUID"
      case .json: return "JSON"
      case .integer, .decimal, .boolean, .text: return ""
      }
    }
    if field.isIdentity { return "DEFAULT (auto)" }
    switch field.kind {
    case .date: return "DEFAULT · yyyy-MM-dd"
    case .timestamp: return "DEFAULT · yyyy-MM-dd HH:mm:ss"
    case .uuid: return "DEFAULT · UUID"
    case .json: return "DEFAULT · JSON"
    case .integer, .decimal, .boolean, .text: return "DEFAULT"
    }
  }

  /// Read-only stand-in for the input, in the NULL style of the cell value view
  private func placeholderBox(_ text: String, italic: Bool = true) -> some View {
    Text(text)
      .font(.monoMedium)
      .italic(italic)
      .foregroundColor(.foregroundSubtle)
      .frame(maxWidth: .infinity, alignment: .leading)
      .padding(Spacing.sm)
      .background(Color.tableHeaderBackground)
      .clipShape(RoundedRectangle(cornerRadius: CornerRadius.md))
  }

  /// Pretty-prints valid JSON in place. Invalid JSON keeps its text and its error.
  private func beautify() {
    guard let data = field.text.data(using: .utf8),
      let object = try? JSONSerialization.jsonObject(with: data, options: .allowFragments),
      let pretty = try? JSONSerialization.data(
        withJSONObject: object, options: [.prettyPrinted, .fragmentsAllowed]),
      let text = String(data: pretty, encoding: .utf8)
    else { return }
    field.text = text
  }
}
