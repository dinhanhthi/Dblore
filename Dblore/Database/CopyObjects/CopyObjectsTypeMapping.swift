// CopyObjectsTypeMapping.swift
// Copy Objects: the target column for a source column. Sources are PostgreSQL, MySQL / MariaDB,
// SQLite and DuckDB; targets PostgreSQL, MySQL / MariaDB and SQLite (DuckDB is never a target).
//
// The source type (`columnType ?? dataType`, as the catalog prints it) is read into a family:
// integers (width, unsigned), decimal(p,s), floats, boolean, text (char(n), varchar(n), varchar
// without a length, unbounded), binary, MySQL BIT and spatial types (bytes: hex on the wire, as
// MySQL's own dumps write them), JSON, uuid, date / time / timestamp / timestamptz, structured
// (PostgreSQL and DuckDB arrays, DuckDB LIST / STRUCT / MAP / UNION), enumerations, and types
// with no counterpart. The same engine keeps the type text verbatim, except PostgreSQL user
// types (enum, domain, composite, range, arrays of them: any type that is not a PostgreSQL
// built-in), which become text with a warning. Across engines each family has one target type;
// structured values become JSON text and types with no counterpart become text, both with a
// warning; MySQL BIT and spatial values become bytes with a warning. On a MySQL / MariaDB target, unbounded text (or binary) that is part of a key or index
// becomes VARCHAR(255) (VARBINARY(255)), other unbounded text LONGTEXT, varchar without a length
// VARCHAR(255).
//
// Identity (PostgreSQL identity and serial, MySQL AUTO_INCREMENT, SQLite INTEGER PRIMARY KEY)
// becomes the target's form: GENERATED BY DEFAULT AS IDENTITY (the copied rows carry their own
// values; the sequence restarts after them), AUTO_INCREMENT on a column that leads a key, or the
// SQLite rowid alias for a single-column INTEGER primary key. Only literal defaults (a string, a
// number, TRUE / FALSE, a PostgreSQL `'x'::type`) are copied; any other default is dropped with a
// warning, except the identity's own `nextval(...)`. Across engines a string default with
// backslash escapes (MySQL, PostgreSQL `E'..'`) is dropped too: its escapes are not decoded.
//
// Binds are text (`SQLBindValue`), so binary values travel as hex: the bind form says how the
// placeholder decodes them. The value form tells the run how to normalize a value before binding.

import Foundation

nonisolated enum CopyObjectsTypeMapping {
  typealias Engine = StructureDDLBuilder.Engine

  /// How a row value of the column is written into the INSERT
  enum BindForm: Sendable, Equatable {
    case plain
    /// PostgreSQL `decode($n, 'hex')`: the bind is the bytes as hex text
    case postgresHexDecode
    /// MySQL `UNHEX(?)`: the bind is the bytes as hex text
    case mysqlUnhex
    /// SQLite `X'..'` literal of the bytes in the statement text; takes no bind
    case sqliteHexLiteral

    /// The VALUES fragment for `placeholder`. Nil for `.sqliteHexLiteral`, which takes no bind
    /// (see `sqliteHexLiteral(_:)`).
    func fragment(placeholder: String) -> String? {
      switch self {
      case .plain: placeholder
      case .postgresHexDecode: "decode(\(placeholder), 'hex')"
      case .mysqlUnhex: "UNHEX(\(placeholder))"
      case .sqliteHexLiteral: nil
      }
    }
  }

  /// How a source value is normalized before it is bound
  enum ValueForm: Sendable, Equatable {
    case asIs
    /// true / false on PostgreSQL, 1 / 0 on MySQL and SQLite
    case boolean
    case date
    case time
    case timestamp
    /// An instant (timestamptz): written in UTC
    case timestampUTC
    /// A PostgreSQL array or DuckDB LIST / STRUCT / MAP: written as JSON text
    case jsonText
    /// Lowercase 8-4-4-4-12 text
    case uuid
  }

  /// The column's numbering on the target
  enum IdentityForm: Sendable, Equatable {
    /// PostgreSQL GENERATED BY DEFAULT AS IDENTITY; its sequence restarts after the rows
    case generatedByDefault
    /// MySQL AUTO_INCREMENT
    case autoIncrement
    /// SQLite INTEGER PRIMARY KEY (an alias of the rowid)
    case rowid
  }

  /// Where the column sits in its table, for the rules that depend on keys
  struct Context: Sendable, Equatable {
    /// The table's primary key columns, in key order
    var primaryKey: [String]
    /// The column is the first column of the primary key or of a unique constraint
    var leadsKey: Bool
    /// The column is in the primary key, a unique constraint, a foreign key or an index
    var isKeyed: Bool

    init(primaryKey: [String], leadsKey: Bool, isKeyed: Bool) {
      self.primaryKey = primaryKey
      self.leadsKey = leadsKey
      self.isKeyed = isKeyed
    }

    init(column: String, in table: TableStructure) {
      primaryKey = CopyObjectsTypeMapping.primaryKey(of: table)
      let uniques = table.constraints.filter { $0.kind == .unique }.map(\.columns)
      leadsKey =
        primaryKey.first == column || uniques.contains { $0.first == column }
      let indexed = table.indexes.contains { index in
        index.keys.contains { $0 == .column(column) }
      }
      isKeyed =
        indexed
        || table.constraints.contains { constraint in
          if case .check = constraint.kind { return false }
          return constraint.columns.contains(column)
        }
    }
  }

  struct Mapping: Sendable, Equatable {
    /// Type text as CREATE TABLE writes it, with the identity clause
    var type: String
    /// Literal DEFAULT text for the target. Nil for none.
    var defaultExpression: String?
    var identity: IdentityForm?
    var bindForm: BindForm
    var valueForm: ValueForm
    /// One sentence each, without the column name
    var warnings: [String]
  }

  /// The table's primary key columns in key order (the constraint, else the primary index)
  static func primaryKey(of table: TableStructure) -> [String] {
    if let key = table.constraints.first(where: { $0.kind == .primaryKey }) {
      return key.columns
    }
    guard let index = table.indexes.first(where: \.isPrimary) else { return [] }
    return index.keys.compactMap { if case .column(let name) = $0 { name } else { nil } }
  }

  /// SQLite `X'..'` for `bytes` (the one place a source value becomes SQL text)
  static func sqliteHexLiteral(_ bytes: Data) -> String {
    "X'" + bytes.map { String(format: "%02X", $0) }.joined() + "'"
  }

  static func map(
    _ column: TableStructure.Column, context: Context, from source: Engine, to target: Engine
  ) throws -> Mapping {
    if case .duckdb = target {
      throw StructureDDLError.unsupported("DuckDB cannot be a Copy Objects target.")
    }
    let sourceType = column.columnType ?? column.dataType
    let family = Self.family(of: column, source: source)
    var warnings: [String] = []
    var type: String
    let sameEngine = source.dialect == target.dialect
    var verbatim = false
    if sameEngine, !(source == .postgresql && family.isUserType) {
      type = sourceType
      verbatim = true
    } else {
      if sameEngine {
        warnings.append("The user type \"\(sourceType)\" is copied as text.")
      }
      let rendered = render(
        sameEngine ? .unknown(userType: true) : family, sourceType: sourceType,
        keyed: context.isKeyed, target: target)
      type = rendered.type
      warnings += rendered.warnings
    }

    var identity: IdentityForm?
    let isIdentity = Self.isIdentity(column, context: context, source: source)
    if isIdentity {
      let placed = identityForm(
        family: family, type: type, column: column.name, context: context, target: target)
      identity = placed.form
      type = placed.type
      warnings += placed.warnings
      if case .sqlite = source, case .sqlite = target, column.identity == .autoIncrement {
        warnings.append("AUTOINCREMENT is not kept: the rowid numbering is.")
      }
    }

    var defaultExpression: String?
    if !isIdentity, let text = column.defaultExpression {
      let restated = restatedDefault(
        text, family: family, verbatim: verbatim, type: type, source: source, target: target)
      defaultExpression = restated.text
      warnings += restated.warnings
    }

    return Mapping(
      type: type, defaultExpression: defaultExpression, identity: identity,
      bindForm: family.isBytes ? binaryBindForm(target) : .plain,
      // A PostgreSQL array kept as an array takes the array text as it is
      valueForm: verbatim && family == .structured ? .asIs : family.valueForm,
      warnings: warnings)
  }

  // MARK: - Families

  enum TextKind: Equatable {
    case fixed(Int)
    case varying(Int)
    /// varchar without a length
    case varyingUnbounded
    /// text, CLOB, DuckDB VARCHAR
    case unbounded
  }

  enum Family: Equatable {
    case integer(bytes: Int, unsigned: Bool)
    case decimal(precision: Int?, scale: Int?)
    case float(double: Bool)
    case boolean
    case text(TextKind)
    case binary
    /// MySQL BIT: bytes
    case bit
    /// MySQL spatial types: bytes in MySQL's geometry format (SRID, then WKB)
    case spatial
    case json
    case uuid
    case date
    case time
    case timestamp
    case timestampWithTimeZone
    case structured
    /// MySQL ENUM / SET, DuckDB ENUM
    case enumeration
    /// A type with no counterpart on other engines. `userType`: not a PostgreSQL built-in.
    case unknown(userType: Bool)

    var isUserType: Bool { self == .unknown(userType: true) }

    /// Read as hex and bound through the target's binary form
    var isBytes: Bool { self == .binary || self == .bit || self == .spatial }

    var valueForm: ValueForm {
      switch self {
      case .boolean: .boolean
      case .date: .date
      case .time: .time
      case .timestamp: .timestamp
      case .timestampWithTimeZone: .timestampUTC
      case .structured: .jsonText
      case .uuid: .uuid
      default: .asIs
      }
    }
  }

  /// A lowercased type name without its parameters and array suffix
  struct TypeName: Equatable {
    var base: String
    var parameters: [Int]
    var isArray: Bool
  }

  static func typeName(_ text: String) -> TypeName {
    var scalars = Array(SQLTokenizer.asciiLowercased(text).unicodeScalars)
    var isArray = false
    // `integer[]`, `INTEGER[3]`, `text[][]`
    while let last = scalars.last, last == "]", let open = scalars.lastIndex(of: "[") {
      scalars.removeSubrange(open...)
      isArray = true
      while let end = scalars.last, SQLTokenizer.isWhitespace(end) { scalars.removeLast() }
    }
    var parameters: [Int] = []
    var base = scalars
    if let open = scalars.firstIndex(of: "("), let close = scalars.lastIndex(of: ")"),
      open < close
    {
      let inner = String(String.UnicodeScalarView(scalars[(open + 1)..<close]))
      let parts = inner.split(separator: ",").map {
        Int($0.trimmingCharacters(in: .whitespaces))
      }
      parameters = parts.allSatisfy { $0 != nil } ? parts.compactMap { $0 } : []
      base = Array(scalars[..<open]) + Array(scalars[(close + 1)...])
    }
    let words = String(String.UnicodeScalarView(base)).split(whereSeparator: \.isWhitespace)
    return TypeName(base: words.joined(separator: " "), parameters: parameters, isArray: isArray)
  }

  static func family(of column: TableStructure.Column, source: Engine) -> Family {
    switch source {
    case .postgresql: return postgresFamily(column.dataType)
    case .mysql: return mysqlFamily(column)
    case .sqlite: return sqliteFamily(column.dataType)
    case .duckdb: return duckdbFamily(column.dataType)
    }
  }

  /// PostgreSQL built-ins with no counterpart elsewhere: kept between PostgreSQL servers
  private static let postgresOtherBuiltins: Set<String> = [
    "inet", "cidr", "macaddr", "macaddr8", "money", "xml", "tsvector", "tsquery", "point",
    "line", "lseg", "box", "path", "polygon", "circle", "bit", "bit varying", "int4range",
    "int8range", "numrange", "tsrange", "tstzrange", "daterange", "int4multirange",
    "int8multirange", "nummultirange", "tsmultirange", "tstzmultirange", "datemultirange", "oid",
    "xid", "xid8", "cid", "tid", "regclass", "regproc", "regprocedure", "regoper",
    "regoperator", "regtype", "regconfig", "regdictionary", "regnamespace", "regrole",
    "regcollation", "pg_lsn", "pg_snapshot", "txid_snapshot", "jsonpath", "name", "\"char\"",
    "time with time zone",
  ]

  private static func postgresFamily(_ text: String) -> Family {
    let name = typeName(text)
    let element = postgresElementFamily(name)
    guard name.isArray else { return element }
    return element.isUserType ? element : .structured
  }

  private static func postgresElementFamily(_ name: TypeName) -> Family {
    let size = name.parameters.first
    switch name.base {
    case "smallint": return .integer(bytes: 2, unsigned: false)
    case "integer": return .integer(bytes: 4, unsigned: false)
    case "bigint": return .integer(bytes: 8, unsigned: false)
    case "numeric":
      return .decimal(precision: size, scale: name.parameters.count > 1 ? name.parameters[1] : nil)
    case "real": return .float(double: false)
    case "double precision": return .float(double: true)
    case "boolean": return .boolean
    case "text", "bpchar": return .text(.unbounded)
    case "character varying": return .text(size.map { .varying($0) } ?? .varyingUnbounded)
    case "character": return .text(.fixed(size ?? 1))
    case "bytea": return .binary
    case "json", "jsonb": return .json
    case "uuid": return .uuid
    case "date": return .date
    case "time", "time without time zone": return .time
    case "timestamp", "timestamp without time zone": return .timestamp
    case "timestamp with time zone": return .timestampWithTimeZone
    default:
      if postgresOtherBuiltins.contains(name.base) || name.base.hasPrefix("interval") {
        return .unknown(userType: false)
      }
      return .unknown(userType: true)
    }
  }

  private static func mysqlFamily(_ column: TableStructure.Column) -> Family {
    let full = SQLTokenizer.asciiLowercased(column.columnType ?? column.dataType)
    let name = typeName(column.columnType ?? column.dataType)
    let unsigned = full.contains("unsigned")
    let size = name.parameters.first
    switch SQLTokenizer.asciiLowercased(column.dataType) {
    case "tinyint":
      return full == "tinyint(1)" ? .boolean : .integer(bytes: 1, unsigned: unsigned)
    case "bool", "boolean": return .boolean
    case "smallint": return .integer(bytes: 2, unsigned: unsigned)
    case "mediumint": return .integer(bytes: 3, unsigned: unsigned)
    case "int", "integer": return .integer(bytes: 4, unsigned: unsigned)
    case "bigint": return .integer(bytes: 8, unsigned: unsigned)
    case "year": return .integer(bytes: 2, unsigned: false)
    case "decimal", "numeric", "dec", "fixed":
      return .decimal(
        precision: size ?? 10, scale: name.parameters.count > 1 ? name.parameters[1] : 0)
    case "float": return .float(double: false)
    case "double", "real", "double precision": return .float(double: true)
    case "char": return .text(.fixed(size ?? 1))
    case "varchar": return .text(size.map { .varying($0) } ?? .varyingUnbounded)
    case "tinytext", "text", "mediumtext", "longtext": return .text(.unbounded)
    case "binary", "varbinary", "tinyblob", "blob", "mediumblob", "longblob": return .binary
    case "bit": return .bit
    case "geometry", "point", "linestring", "polygon", "multipoint", "multilinestring",
      "multipolygon", "geometrycollection", "geomcollection":
      return .spatial
    case "json": return .json
    case "date": return .date
    case "time": return .time
    case "datetime", "timestamp": return .timestamp
    case "enum", "set": return .enumeration
    default: return .unknown(userType: false)
    }
  }

  /// Declared type names first, then SQLite's affinity rules (INT, CHAR / CLOB / TEXT, BLOB,
  /// REAL / FLOA / DOUB). Lengths are not enforced by SQLite, so text is unbounded.
  private static func sqliteFamily(_ text: String) -> Family {
    let base = SQLTokenizer.asciiUppercased(typeName(text).base)
    switch base {
    case "BOOLEAN", "BOOL": return .boolean
    case "DATE": return .date
    case "DATETIME", "TIMESTAMP": return .timestamp
    case "TIME": return .time
    case "JSON": return .json
    case "UUID": return .uuid
    case "DECIMAL", "NUMERIC": return .decimal(precision: nil, scale: nil)
    default: break
    }
    if base.contains("INT") { return .integer(bytes: 8, unsigned: false) }
    if base.contains("CHAR") || base.contains("CLOB") || base.contains("TEXT") {
      return .text(.unbounded)
    }
    if base.contains("BLOB") { return .binary }
    if base.contains("REAL") || base.contains("FLOA") || base.contains("DOUB") {
      return .float(double: true)
    }
    return .unknown(userType: false)
  }

  private static func duckdbFamily(_ text: String) -> Family {
    let name = typeName(text)
    if name.isArray { return .structured }
    for prefix in ["struct(", "map(", "union("]
    where SQLTokenizer.asciiLowercased(text).hasPrefix(prefix) {
      return .structured
    }
    switch name.base {
    case "tinyint": return .integer(bytes: 1, unsigned: false)
    case "smallint": return .integer(bytes: 2, unsigned: false)
    case "integer": return .integer(bytes: 4, unsigned: false)
    case "bigint": return .integer(bytes: 8, unsigned: false)
    case "hugeint": return .integer(bytes: 16, unsigned: false)
    case "utinyint": return .integer(bytes: 1, unsigned: true)
    case "usmallint": return .integer(bytes: 2, unsigned: true)
    case "uinteger": return .integer(bytes: 4, unsigned: true)
    case "ubigint": return .integer(bytes: 8, unsigned: true)
    case "uhugeint": return .integer(bytes: 16, unsigned: true)
    case "decimal":
      return .decimal(
        precision: name.parameters.first,
        scale: name.parameters.count > 1 ? name.parameters[1] : nil)
    case "float", "real": return .float(double: false)
    case "double": return .float(double: true)
    case "boolean": return .boolean
    case "varchar": return .text(.unbounded)
    case "blob": return .binary
    case "json": return .json
    case "uuid": return .uuid
    case "date": return .date
    case "time": return .time
    case "timestamp", "timestamp_s", "timestamp_ms", "timestamp_ns": return .timestamp
    case "timestamp with time zone": return .timestampWithTimeZone
    case "enum": return .enumeration
    default: return .unknown(userType: false)
    }
  }

  // MARK: - Target types

  private static func render(
    _ family: Family, sourceType: String, keyed: Bool, target: Engine
  ) -> (type: String, warnings: [String]) {
    switch family {
    case .integer(let bytes, let unsigned):
      return integerType(bytes: bytes, unsigned: unsigned, target: target)
    case .decimal(let precision, let scale):
      return decimalType(precision: precision, scale: scale, target: target)
    case .float(let double):
      switch target {
      case .postgresql: return (double ? "double precision" : "real", [])
      case .mysql: return (double ? "double" : "float", [])
      case .sqlite, .duckdb: return ("REAL", [])
      }
    case .boolean:
      switch target {
      case .postgresql: return ("boolean", [])
      case .mysql: return ("TINYINT(1)", [])
      case .sqlite, .duckdb: return ("INTEGER", [])
      }
    case .text(let kind):
      return textType(kind, keyed: keyed, target: target)
    case .binary:
      switch target {
      case .postgresql: return ("bytea", [])
      case .mysql:
        guard keyed else { return ("LONGBLOB", []) }
        return (
          "VARBINARY(255)",
          ["Part of a key or index: copied as VARBINARY(255), so longer values fail."]
        )
      case .sqlite, .duckdb: return ("BLOB", [])
      }
    case .bit, .spatial:
      let bytes = render(.binary, sourceType: sourceType, keyed: keyed, target: target)
      let form = family == .spatial ? " in MySQL's geometry format (SRID, then WKB)" : ""
      return (bytes.type, ["\"\(sourceType)\" is copied as bytes\(form)."] + bytes.warnings)
    case .json:
      switch target {
      case .postgresql: return ("jsonb", [])
      case .mysql: return ("JSON", [])
      case .sqlite, .duckdb: return ("TEXT", [])
      }
    case .uuid:
      switch target {
      case .postgresql: return ("uuid", [])
      case .mysql: return ("CHAR(36)", [])
      case .sqlite, .duckdb: return ("TEXT", [])
      }
    case .date:
      switch target {
      case .postgresql: return ("date", [])
      case .mysql: return ("DATE", [])
      case .sqlite, .duckdb: return ("DATE", [])
      }
    case .time:
      switch target {
      case .postgresql: return ("time", [])
      case .mysql: return ("TIME(6)", [])
      case .sqlite, .duckdb: return ("TIME", [])
      }
    case .timestamp:
      switch target {
      case .postgresql: return ("timestamp", [])
      case .mysql: return ("DATETIME(6)", [])
      case .sqlite, .duckdb: return ("DATETIME", [])
      }
    case .timestampWithTimeZone:
      switch target {
      case .postgresql: return ("timestamp with time zone", [])
      case .mysql:
        return ("DATETIME(6)", ["Copied as DATETIME(6) in UTC: the time zone is not kept."])
      case .sqlite, .duckdb: return ("DATETIME", [])
      }
    case .structured:
      let json: String
      switch target {
      case .postgresql: json = "jsonb"
      case .mysql: json = "JSON"
      case .sqlite, .duckdb: json = "TEXT"
      }
      return (json, ["\"\(sourceType)\" is copied as JSON text."])
    case .enumeration:
      let text = textType(.unbounded, keyed: keyed, target: target)
      return (
        text.type,
        ["\"\(sourceType)\" is copied as text: its allowed values are not kept."] + text.warnings
      )
    case .unknown(let userType):
      let text = textType(.unbounded, keyed: keyed, target: target)
      // A same-engine user type already carries its own warning
      let note =
        userType && target == .postgresql
        ? []
        : ["\"\(sourceType)\" has no \(target.dialect.promptName) counterpart: copied as text."]
      return (text.type, note + text.warnings)
    }
  }

  private static func integerType(
    bytes: Int, unsigned: Bool, target: Engine
  ) -> (type: String, warnings: [String]) {
    // The smallest signed type that holds every value
    let needed = unsigned ? bytes * 2 : bytes
    switch target {
    case .postgresql:
      switch needed {
      case ...2: return ("smallint", [])
      case ...4: return ("integer", [])
      case ...8: return ("bigint", [])
      default: return ("numeric(\(bytes > 8 ? 39 : 20),0)", [])
      }
    case .mysql:
      let suffix = unsigned ? " unsigned" : ""
      switch bytes {
      case 1: return ("tinyint" + suffix, [])
      case 2: return ("smallint" + suffix, [])
      case 3: return ("mediumint" + suffix, [])
      case 4: return ("int" + suffix, [])
      case 8: return ("bigint" + suffix, [])
      default: return ("decimal(39,0)" + suffix, [])
      }
    case .sqlite, .duckdb:
      guard needed > 8 else { return ("INTEGER", []) }
      return ("INTEGER", ["Values beyond the 64-bit integer range lose precision on SQLite."])
    }
  }

  private static func decimalType(
    precision: Int?, scale: Int?, target: Engine
  ) -> (type: String, warnings: [String]) {
    switch target {
    case .postgresql:
      guard let precision else { return ("numeric", []) }
      return ("numeric(\(precision),\(scale ?? 0))", [])
    case .mysql:
      // MySQL: precision at most 65, scale at most 30
      guard let precision, precision <= 65, (scale ?? 0) <= 30 else {
        let scale = min(scale ?? 30, 30)
        return (
          "decimal(65,\(scale))",
          ["Copied as decimal(65,\(scale)): values beyond that range or scale do not fit."]
        )
      }
      return ("decimal(\(precision),\(scale ?? 0))", [])
    case .sqlite, .duckdb:
      return ("NUMERIC", [])
    }
  }

  private static func textType(
    _ kind: TextKind, keyed: Bool, target: Engine
  ) -> (type: String, warnings: [String]) {
    switch target {
    case .postgresql:
      switch kind {
      case .fixed(let length): return ("character(\(length))", [])
      case .varying(let length): return ("character varying(\(length))", [])
      case .varyingUnbounded: return ("character varying", [])
      case .unbounded: return ("text", [])
      }
    case .mysql:
      let capped = "Copied as VARCHAR(255), so longer values fail."
      switch kind {
      case .fixed(let length) where length <= 255: return ("CHAR(\(length))", [])
      case .varying(let length) where length <= 16_383: return ("VARCHAR(\(length))", [])
      case .varyingUnbounded:
        return ("VARCHAR(255)", ["A varchar without a length: " + capped])
      case .fixed, .varying, .unbounded:
        guard keyed else { return ("LONGTEXT", []) }
        return ("VARCHAR(255)", ["Unbounded text in a key or index: " + capped])
      }
    case .sqlite, .duckdb:
      return ("TEXT", [])
    }
  }

  private static func binaryBindForm(_ target: Engine) -> BindForm {
    switch target {
    case .postgresql: .postgresHexDecode
    case .mysql: .mysqlUnhex
    case .sqlite, .duckdb: .sqliteHexLiteral
    }
  }

  // MARK: - Identity

  /// Identity, serial (`nextval(...)` default), AUTO_INCREMENT, or a SQLite single-column
  /// INTEGER primary key
  private static func isIdentity(
    _ column: TableStructure.Column, context: Context, source: Engine
  ) -> Bool {
    if column.identity != nil { return true }
    switch source {
    case .postgresql:
      guard let text = column.defaultExpression else { return false }
      return SQLTokenizer.asciiLowercased(text).hasPrefix("nextval(")
    case .sqlite:
      return context.primaryKey == [column.name]
        && SQLTokenizer.asciiUppercased(column.dataType) == "INTEGER"
    case .mysql, .duckdb:
      return false
    }
  }

  private static func identityForm(
    family: Family, type: String, column: String, context: Context, target: Engine
  ) -> (form: IdentityForm?, type: String, warnings: [String]) {
    let lost = "Its numbering is not kept: the values are copied as they are."
    guard case .integer = family else { return (nil, type, [lost]) }
    switch target {
    case .postgresql:
      guard ["smallint", "integer", "bigint"].contains(SQLTokenizer.asciiLowercased(type)) else {
        return (nil, type, [lost])
      }
      return (.generatedByDefault, type + " GENERATED BY DEFAULT AS IDENTITY", [])
    case .mysql:
      // MySQL needs an AUTO_INCREMENT column to lead a key
      guard context.leadsKey else { return (nil, type, [lost]) }
      return (.autoIncrement, type + " AUTO_INCREMENT", [])
    case .sqlite, .duckdb:
      guard context.primaryKey == [column] else { return (nil, type, [lost]) }
      return (.rowid, "INTEGER", [])
    }
  }

  // MARK: - Defaults

  private enum Literal: Equatable {
    case null
    case boolean(Bool)
    case number(String)
    case string(String)
  }

  private static func restatedDefault(
    _ text: String, family: Family, verbatim: Bool, type: String, source: Engine,
    target: Engine
  ) -> (text: String?, warnings: [String]) {
    let dropped = "The default \(text) is not copied."
    guard let literal = literal(text, dialect: source.dialect) else {
      return (nil, ["The default \(text) is not copied: only literal defaults are."])
    }
    if literal == .null { return (nil, []) }
    if case .mysql(let server) = target, server.flavor == .mysql {
      let upper = SQLTokenizer.asciiUppercased(type)
      if upper.hasSuffix("TEXT") || upper.hasSuffix("BLOB") || upper == "JSON" {
        return (nil, [dropped + " MySQL keeps no literal default on TEXT, BLOB or JSON."])
      }
    }
    if verbatim { return (text, []) }
    if case .string = literal, hasEscapes(text, source: source) { return (nil, [dropped]) }
    switch family {
    case .boolean:
      guard let flag = booleanValue(literal) else { return (nil, [dropped]) }
      if case .postgresql = target { return (flag ? "TRUE" : "FALSE", []) }
      return (flag ? "1" : "0", [])
    case .binary, .bit, .spatial, .structured:
      return (nil, [dropped])
    default:
      break
    }
    switch literal {
    case .null: return (nil, [])
    case .boolean(let flag): return (flag ? "TRUE" : "FALSE", [])
    case .number(let number): return (number, [])
    case .string(let content):
      // CREATE TABLE refuses control characters in a default
      guard
        !content.unicodeScalars.contains(where: {
          $0.value < 0x20 && !"\t\n\r".unicodeScalars.contains($0)
        })
      else { return (nil, [dropped]) }
      return (target.dialect.literal(.string(content)), [])
    }
  }

  /// A string default whose escapes the token content keeps undecoded: a MySQL string with a
  /// backslash, a PostgreSQL `E'..'` string
  private static func hasEscapes(_ text: String, source: Engine) -> Bool {
    switch source {
    case .mysql:
      return text.contains("\\")
    case .postgresql:
      let scalars = Array(text.trimmingCharacters(in: .whitespacesAndNewlines).unicodeScalars)
      return scalars.count > 1 && (scalars[0] == "E" || scalars[0] == "e") && scalars[1] == "'"
    case .sqlite, .duckdb:
      return false
    }
  }

  /// A string (PostgreSQL / DuckDB: with an optional `::type` cast), a signed number, NULL,
  /// TRUE or FALSE. Anything else is nil.
  private static func literal(_ text: String, dialect: SQLDialect) -> Literal? {
    let tokens = SQLTokenizer(dialect: dialect).tokens(text)
    guard let first = tokens.first else { return nil }
    if tokens.count == 1 {
      switch first.keyword {
      case "NULL": return .null
      case "TRUE": return .boolean(true)
      case "FALSE": return .boolean(false)
      default: break
      }
    }
    if first.kind == .string {
      // A dollar-quoted string keeps its tags in the token text
      guard !text.trimmingCharacters(in: .whitespacesAndNewlines).hasPrefix("$") else {
        return nil
      }
      let rest = tokens.dropFirst()
      if rest.isEmpty { return .string(first.text) }
      guard dialect == .postgresql || dialect == .duckdb, rest.count >= 3,
        rest.prefix(2).allSatisfy({ $0.isSymbol(":") }),
        rest.dropFirst(2).allSatisfy({ token in
          token.kind == .word || token.kind == .quotedIdentifier
            || ["(", ")", ",", "[", "]", "."].contains { token.isSymbol($0) }
        })
      else { return nil }
      return .string(first.text)
    }
    var parts = tokens[...]
    var number = ""
    if let sign = parts.first, sign.isSymbol("-") || sign.isSymbol("+") {
      if sign.isSymbol("-") { number = "-" }
      parts = parts.dropFirst()
    }
    switch parts.count {
    case 1 where parts[parts.startIndex].kind == .word:
      guard let digits = parts.first?.keyword, digits.allSatisfy(\.isNumber) else { return nil }
      return .number(number + digits)
    case 3:
      let whole = parts[parts.startIndex]
      let point = parts[parts.startIndex + 1]
      let fraction = parts[parts.startIndex + 2]
      guard point.isSymbol("."), let w = whole.keyword, let f = fraction.keyword,
        (w + f).allSatisfy(\.isNumber)
      else { return nil }
      return .number(number + w + "." + f)
    default:
      return nil
    }
  }

  private static func booleanValue(_ literal: Literal) -> Bool? {
    switch literal {
    case .boolean(let flag): return flag
    case .number(let text): return text == "1" ? true : text == "0" ? false : nil
    case .string(let text):
      switch SQLTokenizer.asciiLowercased(text) {
      case "t", "true", "1", "y", "yes", "on": return true
      case "f", "false", "0", "n", "no", "off": return false
      default: return nil
      }
    case .null: return nil
    }
  }
